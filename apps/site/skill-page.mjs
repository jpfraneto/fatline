#!/usr/bin/env node
// Writes fatline.ink/skill/ (skill/index.html) from skill.md. GitHub Pages serves skill.md as plain markdown,
// which has nowhere to put a link preview, so the page to share is /skill: the same instructions, with a
// preview image (Farcaster, Telegram, X) and the line to paste into an agent. Agents can read either one:
// the full markdown is in the page as text. Run by the site workflow; run it by hand after editing skill.md.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const md = readFileSync(join(here, 'skill.md'), 'utf8');
const esc = (s) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const body = md.replace(/^---\n[\s\S]*?\n---\n/, ''); // the front matter is for agents' skill loaders

const URL = 'https://fatline.ink/skill';
const IMG = 'https://fatline.ink/img/og/og-skill.jpg';
const TITLE = 'Teach your agent to run Farcaster';
const DESC = 'One line to Claude, ChatGPT or Grok, and it sets up your own Farcaster node, your own client, and an egg that hatches from your history.';
const PROMPT = 'Help me run a Fatline: https://fatline.ink/skill.md';
const embed = (type) => esc(JSON.stringify({ version: '1', imageUrl: IMG, button: { title: 'Run your own', action: { type, name: 'Fatline', url: URL, splashImageUrl: 'https://fatline.ink/img/fatline-app.png', splashBackgroundColor: '#1a120b' } } }));

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Fatline skill</title>
<!-- Generated by apps/site/skill-page.mjs from skill.md. Edit skill.md, not this file. -->
<meta name="description" content="${esc(DESC)}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Fatline">
<meta property="og:title" content="${esc(TITLE)}">
<meta property="og:description" content="${esc(DESC)}">
<meta property="og:url" content="${URL}">
<meta property="og:image" content="${IMG}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="Fatliner figurines teaching three little AI assistant mascots, at golden hour">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(TITLE)}">
<meta name="twitter:description" content="${esc(DESC)}">
<meta name="twitter:image" content="${IMG}">
<meta name="fc:miniapp" content="${embed('launch_miniapp')}">
<meta name="fc:frame" content="${embed('launch_frame')}">
<link rel="alternate" type="text/markdown" href="/skill.md">
<link rel="icon" href="/img/fatline-app.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght,SOFT,WONK@9..144,300..900,0..100,0..1&family=Inter:wght@400;500;600&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet">
<style>
  :root { --bg: #0f1420; --ink: #f3eadb; --muted: #a9a08f; --line: rgba(243,234,219,.14); --accent: #7aa8ff; --card: rgba(255,255,255,.035);
    --display: "Fraunces", Georgia, serif; --body: "Inter", system-ui, sans-serif; --mono: "JetBrains Mono", ui-monospace, monospace; color-scheme: dark; }
  * { box-sizing: border-box; }
  html, body { margin: 0; }
  body { background: radial-gradient(1100px 700px at 50% -10%, rgba(255,170,80,.16), transparent 60%), var(--bg); color: var(--ink); font: 16px/1.6 var(--body); }
  .wrap { max-width: 860px; margin: 0 auto; padding: 18px max(16px, env(safe-area-inset-left, 0px)) 80px; }
  nav { display: flex; justify-content: space-between; align-items: center; font: 500 13px var(--mono); letter-spacing: .3em; }
  nav a { color: var(--ink); text-decoration: none; }
  .hero { margin: 28px 0 0; border-radius: 22px; overflow: hidden; box-shadow: 0 0 0 1px var(--line), 0 30px 80px rgba(0,0,0,.45); }
  .hero img { display: block; width: 100%; height: auto; aspect-ratio: 16 / 9; object-fit: cover; }
  h1 { font: 800 clamp(34px, 7vw, 60px)/1.02 var(--display); font-variation-settings: 'SOFT' 100, 'WONK' 1; margin: 34px 0 10px; text-align: center; }
  .lede { color: var(--muted); text-align: center; max-width: 560px; margin: 0 auto 22px; }
  .copy { display: flex; max-width: 640px; margin: 0 auto; border: 1px solid var(--line); border-radius: 14px; overflow: hidden; background: #0a0d14; }
  .copy code { flex: 1; min-width: 0; padding: 14px 16px; font: 14px var(--mono); overflow-x: auto; white-space: nowrap; }
  .copy code::before { content: "› "; color: var(--accent); }
  .copy button { border: 0; padding: 0 20px; background: var(--ink); color: #111; font: 600 15px var(--body); cursor: pointer; }
  .alt { text-align: center; color: var(--muted); font-size: 14px; margin: 12px 0 0; }
  .alt a { color: var(--ink); }
  .md { margin-top: 48px; padding-top: 28px; border-top: 1px solid var(--line); }
  .md h1 { text-align: left; font-size: 34px; margin: 0 0 12px; }
  .md h2, .md h3 { font-family: var(--display); margin: 1.6em 0 .4em; }
  .md a { color: var(--accent); }
  .md code { font: 13.5px var(--mono); background: var(--card); padding: 1px 5px; border-radius: 5px; }
  .md pre { background: #0a0d14; border: 1px solid var(--line); border-radius: 12px; padding: 14px 16px; overflow-x: auto; }
  .md pre code { background: none; padding: 0; }
  pre#raw { white-space: pre-wrap; word-break: break-word; font: 13.5px/1.6 var(--mono); color: var(--muted); }
</style>
</head>
<body>
<div class="wrap">
<nav><a href="/">FATLINE</a><a href="/docs/">DOCS</a></nav>
<div class="hero"><img src="/img/skill-classroom.jpg" alt="Fatliner figurines teaching three little AI assistant mascots, at golden hour"></div>
<h1>Teach your agent<br>to run Farcaster.</h1>
<p class="lede">Paste this into Claude Code, Codex, or any agent that can run commands. It sets up your own node, your own client, and an egg that hatches from your history. You approve every payment and every signature.</p>
<div class="copy"><code id="prompt">${esc(PROMPT)}</code><button id="copy" type="button">Copy</button></div>
<p class="alt">or do it by hand → <a href="/docs/">the docs</a> · the raw file for agents: <a href="/skill.md">/skill.md</a></p>
<article class="md" id="md"><pre id="raw">${esc(body)}</pre></article>
</div>
<script type="module">
document.getElementById('copy').onclick = async (e) => {
  try { await navigator.clipboard.writeText(document.getElementById('prompt').textContent); e.target.textContent = 'Copied'; } catch { e.target.textContent = 'Select it'; }
  setTimeout(() => (e.target.textContent = 'Copy'), 1600);
};
// Render the markdown for people; without JavaScript (and for agents) it stays readable as plain text.
try {
  const { marked } = await import('https://cdn.jsdelivr.net/npm/marked@12.0.2/lib/marked.esm.js');
  const raw = document.getElementById('raw');
  document.getElementById('md').innerHTML = marked.parse(raw.textContent);
} catch {}
// Inside Farcaster this page is a mini app: tell the host it is ready.
try { const { sdk } = await import('https://esm.sh/@farcaster/miniapp-sdk@0.1.9'); if (await sdk.isInMiniApp()) sdk.actions.ready(); } catch {}
</script>
</body>
</html>
`;
mkdirSync(join(here, 'skill'), { recursive: true });
writeFileSync(join(here, 'skill', 'index.html'), html);
console.log(`wrote ${join(here, 'skill', 'index.html')}`);
